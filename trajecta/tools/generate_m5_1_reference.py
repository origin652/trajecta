CODE_PATTERN = re.compile(r'"([a-z][a-z0-9_-]*(?:\.[a-z][a-z0-9_-]*)+)"')
NON_DIAGNOSTIC_CODES = {"config.toml"}


def default_binary() -> Path:
    suffix = ".exe" if sys.platform == "win32" else ""
    return ROOT / "target" / "debug" / f"trajecta-cli{suffix}"


def binary_help(binary: Path) -> str:
    if not binary.is_file():
        raise RuntimeError(f"CLI binary does not exist: {binary}")
    completed = subprocess.run(
        [str(binary), "--help"],
        cwd=ROOT,
        check=False,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if completed.returncode != 0 or completed.stderr:
        raise RuntimeError(
            f"CLI help failed with exit {completed.returncode}: "
            f"{completed.stderr.decode('utf-8', errors='replace')}"
        )
    return completed.stdout.decode("utf-8").replace("\r\n", "\n").rstrip()


def command_synopses(help_text: str) -> list[str]:
    try:
        block = help_text.split("Commands:\n", 1)[1].split("\n\nmet probe options:", 1)[0]
    except IndexError as error:
        raise RuntimeError("CLI help has no parseable Commands section") from error
    return [line.strip() for line in block.splitlines() if line.strip()]


def command_path(synopsis: str, known: set[str]) -> str:
    matches = [path for path in known if synopsis == path or synopsis.startswith(path + " ")]
    if not matches:
        raise RuntimeError(f"help synopsis has no command contract entry: {synopsis}")
    return max(matches, key=len)


def cli_pages(help_text: str) -> dict[Path, str]:
    contract = json.loads(CONTRACT_PATH.read_text(encoding="utf-8"))
    entries = {entry["path"]: entry for entry in contract["commands"]}
    entries["run report"] = {
        "path": "run report",
        "stage": "m5_a3",
        "owner": "b",
        "streaming": False,
    }
    synopses = command_synopses(help_text)
    paths = [command_path(synopsis, set(entries)) for synopsis in synopses]
    if len(paths) != len(set(paths)):
        raise RuntimeError("CLI help contains a duplicate command synopsis")
    if set(paths) != set(entries):
        missing = sorted(set(entries) - set(paths))
        extra = sorted(set(paths) - set(entries))
        raise RuntimeError(f"CLI help/contract drift: missing={missing}, extra={extra}")

    rows = []
    for synopsis, path in zip(synopses, paths, strict=True):
        entry = entries[path]
        rows.append(
            f"| `{synopsis}` | `{entry['stage']}` | "
            f"{'yes' if entry['streaming'] else 'no'} |"
        )
    en = f"""---
title: CLI command tree
description: Complete Trajecta 0.1.0-alpha.1 command synopsis generated from the real binary help and checked against the frozen CLI contract.
---

{GENERATED_NOTICE}

# CLI command tree

This page is generated from the `trajecta --help` output produced by the current
binary. Every frozen command is cross-checked against
`testdata/M5_CLI_CONTRACT.v1.json`. `run report` is an implemented M5-A3 command
that post-dates the frozen 35-command contract.

## Global rules

- Global options may appear before or after a command.
- Human output is the default. Use `--format json` for one envelope and
  `--format jsonl` for streams.
- `run` waits in the foreground unless `--detach` is supplied.
- `job prune` is dry-run only in this alpha release.

## Commands

| Synopsis | Introduced | Streaming |
| --- | --- | --- |
{chr(10).join(rows)}

## Exact binary help

```text
{help_text}
```
"""
    zh_rows = [
        row.replace("| yes |", "| 是 |").replace("| no |", "| 否 |") for row in rows
    ]
    zh = f"""---
title: CLI 命令树
description: 由真实二进制帮助生成，并与冻结 CLI 合同校验的 Trajecta 0.1.0-alpha.1 完整命令概要。
---

{GENERATED_NOTICE}

# CLI 命令树

本页由当前二进制的 `trajecta --help` 输出生成。冻结命令同时与
`testdata/M5_CLI_CONTRACT.v1.json` 交叉校验。`run report` 是 M5-A3 已实现命令，
其实现时间晚于冻结的 35 条命令合同。

## 全局规则

- 全局选项可以位于命令前后。
- 默认输出供人类阅读。单个机器结果使用 `--format json`，流式结果使用
  `--format jsonl`。
- `run` 默认在前台等待；`--detach` 用于提交后返回。
- 当前 alpha 版本的 `job prune` 只生成 dry-run 计划。

## 命令

| 概要 | 引入阶段 | 流式输出 |
| --- | --- | --- |
{chr(10).join(zh_rows)}

## 二进制原始帮助

```text
{help_text}
```
"""
    return {
        DOCS / "en" / "reference" / "cli.md": en,
        DOCS / "zh-CN" / "reference" / "cli.md": zh,
    }


def schema_rows(locale: str) -> list[str]:
    rows = []
    for name in PRODUCT_SCHEMAS:
        path = ROOT / "testdata" / name
        schema = json.loads(path.read_text(encoding="utf-8"))
        required = schema.get("required", [])
        required_text = ", ".join(f"`{item}`" for item in required) or "—"
        source = f"https://github.com/origin652/trajecta/blob/main/trajecta/testdata/{name}"
        example_name = EXAMPLES.get(name)
        if example_name:
            example_url = (
                "https://github.com/origin652/trajecta/blob/main/trajecta/testdata/"
                + example_name
            )
            example = f"[{example_name}]({example_url})"
        else:
            example = "—"
        title = schema.get("title", name)
        schema_link = f"[{name}]({source})"
        rows.append(f"| {title} | {schema_link} | {example} | {required_text} |")
    return rows


