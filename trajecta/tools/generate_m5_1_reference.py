def diagnostic_sources() -> dict[str, set[str]]:
    roots = (
        ROOT / "crates" / "trajecta-cli" / "src",
        ROOT / "crates" / "trajecta-job" / "src",
    )
    found: dict[str, set[str]] = {}
    for source_root in roots:
        for path in sorted(source_root.rglob("*.rs")):
            relative = path.relative_to(ROOT).as_posix()
            text = path.read_text(encoding="utf-8")
            for code in CODE_PATTERN.findall(text):
                if (
                    code not in NON_DIAGNOSTIC_CODES
                    and code.split(".", 1)[0] in DIAGNOSTIC_PREFIXES
                ):
                    found.setdefault(code, set()).add(relative)
    return found


def diagnostics_pages() -> dict[Path, str]:
    found = diagnostic_sources()
    if not found:
        raise RuntimeError("no source-backed diagnostics found")
    groups: dict[str, list[tuple[str, set[str]]]] = {}
    for code, sources in sorted(found.items()):
        groups.setdefault(code.split(".", 1)[0], []).append((code, sources))

    sections = []
    for prefix, entries in groups.items():
        rows = []
        for code, sources in entries:
            links = []
            for source in sorted(sources):
                url = f"https://github.com/origin652/trajecta/blob/main/trajecta/{source}"
                links.append(f"[`{source}`]({url})")
            rows.append(f"| `{code}` | {', '.join(links)} |")
        sections.append(f"## `{prefix}.*`\n\n| Code | Source |\n| --- | --- |\n" + "\n".join(rows))
    body = "\n\n".join(sections)
    en = f"""---
title: Diagnostic codes
description: Source-backed index of stable Trajecta CLI, daemon, worker, job, project, data, and result diagnostic codes.
---

{GENERATED_NOTICE}

# Diagnostic codes

Machine output identifies a condition by `diagnostics[].code`; messages provide
context and may become more precise. Automation should branch on the code. The
index below is rebuilt from production Rust sources, so a documented code cannot
exist without a corresponding implementation site.

Start troubleshooting by symptom in the [operations index](../operations/troubleshooting.md).

{body}
"""
    zh = f"""---
title: Diagnostic code
description: 由源码生成的 Trajecta CLI、daemon、worker、任务、项目、资料和结果稳定诊断码索引。
---

{GENERATED_NOTICE}

# Diagnostic code

机器输出通过 `diagnostics[].code` 标识条件；message 提供上下文，措辞可能进一步细化。
自动化程序应按 code 分支。下列索引从生产 Rust 源码重建，因此每个已记录 code 都有对应
实现位置。

按症状排查时，请先查阅[运维故障索引](../operations/troubleshooting.md)。

{body}
"""
    return {
        DOCS / "en" / "reference" / "diagnostics.md": en,
        DOCS / "zh-CN" / "reference" / "diagnostics.md": zh,
    }


def generated_pages(help_text: str) -> dict[Path, str]:
    return cli_pages(help_text) | schema_pages() | diagnostics_pages()


def write_or_check(pages: dict[Path, str], check: bool) -> None:
    stale = []
    for path, content in pages.items():
        normalized = content.rstrip() + "\n"
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != normalized:
                stale.append(path.relative_to(ROOT).as_posix())
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(normalized, encoding="utf-8", newline="\n")
    if stale:
        raise RuntimeError("generated reference pages are stale: " + ", ".join(stale))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, default=default_binary())
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    help_text = binary_help(args.binary.resolve())
    pages = generated_pages(help_text)
    write_or_check(pages, args.check)
    print(f"validated {len(pages)} generated reference pages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
