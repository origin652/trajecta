def generated_pages(help_text: str) -> dict[Path, str]:
    return cli_pages(help_text) | schema_pages() | diagnostics_pages()


def write_or_check(pages: dict[Path, str], check: bool) -> None:
    stale = []
    for path, content in pages.items():
        normalized = content.rstrip() + "\n"
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != normalized:
                stale.append(path.relative_to(ROOT).as_posix())
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(normalized, encoding="utf-8", newline="\n")
    if stale:
        raise RuntimeError("generated reference pages are stale: " + ", ".join(stale))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, default=default_binary())
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    help_text = binary_help(args.binary.resolve())
    pages = generated_pages(help_text)
    write_or_check(pages, args.check)
    print(f"validated {len(pages)} generated reference pages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
