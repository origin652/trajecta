def default_binary() -> Path:
    suffix = ".exe" if sys.platform == "win32" else ""
    return ROOT / "target" / "debug" / f"trajecta-cli{suffix}"


def binary_help(binary: Path) -> str:
    if not binary.is_file():
        raise RuntimeError(f"CLI binary does not exist: {binary}")
    completed = subprocess.run(
        [str(binary), "--help"],
        cwd=ROOT,
        check=False,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if completed.returncode != 0 or completed.stderr:
        raise RuntimeError(
            f"CLI help failed with exit {completed.returncode}: "
            f"{completed.stderr.decode('utf-8', errors='replace')}"
        )
    return completed.stdout.decode("utf-8").replace("\r\n", "\n").rstrip()


def command_synopses(help_text: str) -> list[str]:
    try:
        block = help_text.split("Commands:\n", 1)[1].split("\n\nmet probe options:", 1)[0]
    except IndexError as error:
        raise RuntimeError("CLI help has no parseable Commands section") from error
    return [line.strip() for line in block.splitlines() if line.strip()]


def command_path(synopsis: str, known: set[str]) -> str:
    matches = [path for path in known if synopsis == path or synopsis.startswith(path + " ")]
    if not matches:
        raise RuntimeError(f"help synopsis has no command contract entry: {synopsis}")
    return max(matches, key=len)


