def diagnostic_sources() -> dict[str, set[str]]:
    roots = (
        ROOT / "crates" / "trajecta-cli" / "src",
        ROOT / "crates" / "trajecta-job" / "src",
    )
    found: dict[str, set[str]] = {}
    for source_root in roots:
        for path in sorted(source_root.rglob("*.rs")):
            relative = path.relative_to(ROOT).as_posix()
            text = path.read_text(encoding="utf-8")
            for code in CODE_PATTERN.findall(text):
                if (
                    code not in NON_DIAGNOSTIC_CODES
                    and code.split(".", 1)[0] in DIAGNOSTIC_PREFIXES
                ):
                    found.setdefault(code, set()).add(relative)
    return found


