def prepare_trajecta(arguments: argparse.Namespace) -> int:
    root = arguments.output.resolve()
    if root.exists():
        raise ComparisonError(f"refusing to overwrite Trajecta case: {root}")
    data_root = arguments.data.resolve()
    identities = validate_trajecta_data(data_root)
    project_root = root / "project"
    for directory in ("cases", "profiles", "locks", "runs", "data"):
        (project_root / directory).mkdir(parents=True, exist_ok=False)
    for identity in identities:
        source = data_root / str(identity["path"])
        shutil.copy2(source, project_root / "data" / source.name)
    write_json(
        project_root / "cases" / "comparison.json",
        trajecta_case_document(
            arguments.particles,
            arguments.time_step_seconds,
            arguments.output_interval_seconds,
        ),
    )
