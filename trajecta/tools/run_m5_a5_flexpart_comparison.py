class ComparisonError(RuntimeError):
    """Stable M5-A5 preparation failure."""


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_text(path: Path, text: str) -> None:
    path.write_text(text.rstrip("\n") + "\n", encoding="utf-8", newline="\n")


def require_sha256(path: Path, expected: str) -> dict[str, object]:
    if not path.is_file():
        raise ComparisonError(f"required source missing: {path}")
    actual = sha256(path)
    if actual != expected:
        raise ComparisonError(f"source identity mismatch for {path}: {actual}")
    return {"path": path.as_posix(), "size_bytes": path.stat().st_size, "sha256": actual}


def meteorology_name(timestamp: int) -> str:
    instant = datetime.fromtimestamp(timestamp, tz=timezone.utc)
    if instant.strftime("%Y%m%d") != START_DATE or instant.minute or instant.second:
        raise ComparisonError(f"unsupported meteorology time: {instant.isoformat()}")
    return f"EA{instant:%y%m%d%H}"


def _stage_modules():
    try:
        import eccodes  # type: ignore
        import netCDF4  # type: ignore
        import numpy  # type: ignore
    except ImportError as error:
        raise ComparisonError(
            "stage-meteorology requires Python eccodes, netCDF4, and numpy"
        ) from error
    return eccodes, netCDF4, numpy


def _plain_array(numpy, variable, index: int, shape: tuple[int, ...], label: str):
    values = variable[index]
    if numpy.ma.isMaskedArray(values) and numpy.ma.getmaskarray(values).any():
        raise ComparisonError(f"masked values in {label}")
    array = numpy.asarray(values, dtype=numpy.float64)
    while array.ndim > len(shape) and array.shape[0] == 1:
        array = array[0]
    if array.shape != shape:
        raise ComparisonError(f"{label} shape {array.shape} != {shape}")
    if not numpy.isfinite(array).all():
        raise ComparisonError(f"nonfinite values in {label}")
    return array


def _write_grib_message(
    eccodes,
    template,
    stream,
    values,
    instant: datetime,
    *,
    param_id: int | None = None,
    category_number: tuple[int, int] | None = None,
    level_type: str,
    level: int | None = None,
) -> dict[str, object]:
    message = eccodes.codes_clone(template)
    try:
        eccodes.codes_set(message, "dataDate", int(instant.strftime("%Y%m%d")))
        eccodes.codes_set(message, "dataTime", int(instant.strftime("%H%M")))
        eccodes.codes_set(message, "forecastTime", 0)
        eccodes.codes_set(message, "stepRange", 0)
        if level_type != "hybrid":
            eccodes.codes_set(message, "typeOfLevel", level_type)
            if level is None:
                eccodes.codes_set(message, "scaleFactorOfFirstFixedSurface", 0)
                eccodes.codes_set(message, "scaledValueOfFirstFixedSurface", 0)
        if param_id is not None:
            eccodes.codes_set(message, "paramId", param_id)
        elif category_number is not None:
            category, number = category_number
            eccodes.codes_set(message, "discipline", 0)
            eccodes.codes_set(message, "parameterCategory", category)
            eccodes.codes_set(message, "parameterNumber", number)
        else:
            raise ComparisonError("GRIB message is missing a parameter identity")
        if level is not None:
            eccodes.codes_set(message, "level", level)
        eccodes.codes_set_values(message, values.reshape(-1))
        if eccodes.codes_get(message, "NV") != 276:
            raise ComparisonError("generated GRIB message lost the 137-level PV vector")
        eccodes.codes_write(message, stream)
        return {
            "param_id": int(eccodes.codes_get(message, "paramId")),
            "parameter_category": int(eccodes.codes_get(message, "parameterCategory")),
            "parameter_number": int(eccodes.codes_get(message, "parameterNumber")),
            "type_of_level": str(eccodes.codes_get(message, "typeOfLevel")),
            "level": int(eccodes.codes_get(message, "level")),
        }
    finally:
        eccodes.codes_release(message)


def stage_meteorology(arguments: argparse.Namespace) -> int:
    source_root = arguments.source.resolve()
    output = arguments.output.resolve()
    if output.exists():
        raise ComparisonError(f"refusing to overwrite meteorology staging: {output}")

    sources = {
        relative: require_sha256(source_root / relative, expected)
        for relative, expected in SOURCE_IDENTITIES.items()
    }
    eccodes, netcdf4, numpy = _stage_modules()
    hybrid_path = source_root / "raw/era5_hybrid137_20181201.nc"
    lnsp_path = source_root / "raw/era5_lnsp_20181201.nc"
    surface_path = source_root / "raw/era5_hybrid_surface_base_20181201.nc"
    template_path = source_root / "raw/era5_hybrid_pv_probe.grib"

    output.mkdir(parents=True)
    with (
        netcdf4.Dataset(hybrid_path.as_posix()) as hybrid,
        netcdf4.Dataset(lnsp_path.as_posix()) as lnsp,
        netcdf4.Dataset(surface_path.as_posix()) as surface,
        template_path.open("rb") as template_stream,
    ):
        template = eccodes.codes_grib_new_from_file(template_stream)
        if template is None:
            raise ComparisonError("official PV probe contains no GRIB message")
        try:
            times = numpy.asarray(hybrid.variables["valid_time"][:], dtype=numpy.int64)
            if tuple(meteorology_name(int(value)) for value in times) != METEOROLOGY_NAMES:
                raise ComparisonError(f"unexpected hybrid times: {times.tolist()}")
            for companion, label in ((lnsp, "lnsp"), (surface, "surface")):
                companion_times = numpy.asarray(
                    companion.variables["valid_time"][:], dtype=numpy.int64
                )
                if not numpy.array_equal(times, companion_times):
                    raise ComparisonError(f"{label} valid_time differs from hybrid")
                for coordinate in ("latitude", "longitude"):
                    if not numpy.array_equal(
                        hybrid.variables[coordinate][:], companion.variables[coordinate][:]
                    ):
                        raise ComparisonError(f"{label} {coordinate} differs from hybrid")

            levels = len(hybrid.dimensions["model_level"])
            shape = (len(hybrid.dimensions["latitude"]), len(hybrid.dimensions["longitude"]))
            if levels != 137 or shape != (33, 41):
                raise ComparisonError(f"unexpected official hybrid grid: levels={levels} shape={shape}")

            generated = []
            for time_index, timestamp in enumerate(times):
                instant = datetime.fromtimestamp(int(timestamp), tz=timezone.utc)
                name = meteorology_name(int(timestamp))
                path = output / name
                messages = []
                with path.open("xb") as stream:
                    for variable, param_id in (("u", 131), ("v", 132), ("w", 135), ("t", 130)):
                        cube = _plain_array(
                            numpy,
                            hybrid.variables[variable],
                            time_index,
                            (137, *shape),
                            f"{variable}[{time_index}]",
                        )
                        for level_index in range(137):
                            messages.append(
                                _write_grib_message(
                                    eccodes,
                                    template,
                                    stream,
                                    cube[level_index],
                                    instant,
                                    param_id=param_id,
                                    level_type="hybrid",
                                    level=level_index + 1,
                                )
                            )

                    logarithm = _plain_array(
                        numpy, lnsp.variables["lnsp"], time_index, shape, f"lnsp[{time_index}]"
                    )
                    messages.append(
                        _write_grib_message(
                            eccodes,
                            template,
                            stream,
                            numpy.exp(logarithm),
                            instant,
                            param_id=134,
                            level_type="surface",
                        )
                    )

                    humidity = _plain_array(
                        numpy,
                        hybrid.variables["q"],
                        time_index,
                        (137, *shape),
                        f"q[{time_index}]",
                    )
                    for level_index in range(137):
                        messages.append(
                            _write_grib_message(
                                eccodes,
                                template,
                                stream,
                                humidity[level_index],
                                instant,
                                param_id=133,
                                level_type="hybrid",
                                level=level_index + 1,
                            )
                        )

                    zeros = numpy.zeros(shape, dtype=numpy.float64)
                    for category_number in ((1, 9), (1, 10)):
                        messages.append(
                            _write_grib_message(
                                eccodes,
                                template,
                                stream,
                                zeros,
                                instant,
                                category_number=category_number,
                                level_type="surface",
                            )
                        )

                    for variable, param_id, level_type, level in (
                        ("u10", 165, "heightAboveGround", 10),
                        ("v10", 166, "heightAboveGround", 10),
                        ("t2m", 167, "heightAboveGround", 2),
                        ("d2m", 168, "heightAboveGround", 2),
                        ("z", 129, "surface", None),
                    ):
                        messages.append(
                            _write_grib_message(
                                eccodes,
                                template,
                                stream,
                                _plain_array(
                                    numpy,
                                    surface.variables[variable],
                                    time_index,
                                    shape,
                                    f"{variable}[{time_index}]",
                                ),
                                instant,
                                param_id=param_id,
                                level_type=level_type,
                                level=level,
                            )
                        )
                if len(messages) != MESSAGES_PER_FRAME:
                    raise ComparisonError(
                        f"generated {len(messages)} messages for {name}, "
                        f"expected {MESSAGES_PER_FRAME}"
                    )
                generated.append(
                    {
                        "name": name,
                        "valid_time_unix": int(timestamp),
                        "size_bytes": path.stat().st_size,
                        "sha256": sha256(path),
                        "message_count": len(messages),
                    }
                )
        finally:
            eccodes.codes_release(template)

    manifest = {
        "schema_version": METEOROLOGY_SCHEMA_VERSION,
        "source_files": list(sources.values()),
        "generated_files": generated,
        "grid": {"nx": 41, "ny": 33, "full_levels": 137},
        "vertical_velocity": {
            "param_id": 135,
            "unit": "Pa/s",
            "conversion": "none",
        },
        "derived_fields": [
            "surface_pressure_pa = exp(log_surface_pressure)",
            "large_scale_precipitation = 0 because wet deposition is disabled",
            "convective_precipitation = 0 because wet deposition and convection are disabled",
        ],
        "toolchain": {
            "eccodes": str(eccodes.codes_get_api_version()),
            "netcdf4_python": str(netcdf4.__version__),
            "numpy": str(numpy.__version__),
        },
    }
    manifest_path = output / "M5_A5_METEOROLOGY.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(manifest_path)
    return 0


def validate_time_contract(time_step_seconds: int, output_interval_seconds: int) -> None:
    if time_step_seconds <= 0 or output_interval_seconds <= 0:
        raise ComparisonError("time step and output interval must be positive")
    if output_interval_seconds % time_step_seconds != 0:
        raise ComparisonError("output interval must be a multiple of the time step")
    if output_interval_seconds < 2 * time_step_seconds:
        raise ComparisonError(
            "FLEXPART output interval must be at least twice the time step"
        )


