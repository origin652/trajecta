def _array_comparison(numpy, left, right) -> dict[str, object]:
    left_array = numpy.asarray(left)
    right_array = numpy.asarray(right)
    if left_array.shape != right_array.shape:
        return {
            "passed": False,
            "left_shape": list(left_array.shape),
            "right_shape": list(right_array.shape),
            "value_count": 0,
            "maximum_absolute_error": None,
        }
    difference = numpy.abs(left_array.astype(numpy.float64) - right_array.astype(numpy.float64))
    maximum = float(difference.max()) if difference.size else 0.0
    return {
        "passed": bool(numpy.array_equal(left_array, right_array)),
        "left_shape": list(left_array.shape),
        "right_shape": list(right_array.shape),
        "value_count": int(left_array.size),
        "maximum_absolute_error": maximum,
    }


def _packing_comparison(numpy, expected, actual, packing_error: float) -> dict[str, object]:
    expected_array = numpy.asarray(expected, dtype=numpy.float64).reshape(-1)
    actual_array = numpy.asarray(actual, dtype=numpy.float64).reshape(-1)
    if expected_array.shape != actual_array.shape:
        return {
            "passed": False,
            "value_count": 0,
            "maximum_absolute_error": None,
            "packing_error": packing_error,
            "tolerance": None,
        }
    difference = numpy.abs(expected_array - actual_array)
    maximum = float(difference.max()) if difference.size else 0.0
    scale = float(numpy.max(numpy.abs(expected_array))) if expected_array.size else 1.0
    roundoff = float(numpy.finfo(numpy.float64).eps * max(1.0, scale) * 8.0)
    tolerance = packing_error + roundoff
    return {
        "passed": bool(numpy.isfinite(actual_array).all() and maximum <= tolerance),
        "value_count": int(expected_array.size),
        "maximum_absolute_error": maximum,
        "packing_error": packing_error,
        "tolerance": tolerance,
    }


def audit_meteorology(arguments: argparse.Namespace) -> int:
    output = arguments.output.resolve()
