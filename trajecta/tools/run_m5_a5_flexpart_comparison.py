def parse_elapsed_seconds(value: str) -> float:
    parts = value.strip().split(":")
    try:
        numbers = [float(part) for part in parts]
    except ValueError as error:
        raise ComparisonError(f"invalid /usr/bin/time elapsed value: {value}") from error
    if len(numbers) == 2:
        minutes, seconds = numbers
        return minutes * 60.0 + seconds
    if len(numbers) == 3:
        hours, minutes, seconds = numbers
        return hours * 3600.0 + minutes * 60.0 + seconds
    raise ComparisonError(f"invalid /usr/bin/time elapsed value: {value}")


def parse_time_verbose(stderr: str) -> dict[str, object]:
    fields = {
        "User time (seconds)": "user_seconds",
        "System time (seconds)": "system_seconds",
        "Elapsed (wall clock) time (h:mm:ss or m:ss)": "elapsed_seconds",
        "Maximum resident set size (kbytes)": "peak_rss_kib",
        "File system inputs": "filesystem_inputs",
        "File system outputs": "filesystem_outputs",
        "Exit status": "reported_exit_status",
    }
    result: dict[str, object] = {}
    for line in stderr.splitlines():
        stripped = line.strip()
        for source, target in fields.items():
            prefix = source + ":"
            if not stripped.startswith(prefix):
                continue
            value = stripped[len(prefix) :].strip()
            if target == "elapsed_seconds":
                result[target] = parse_elapsed_seconds(value)
            elif target.endswith("_seconds"):
                result[target] = float(value)
            else:
                result[target] = int(value)
            break
    missing = set(fields.values()) - set(result)
    if missing:
        raise ComparisonError(f"incomplete /usr/bin/time -v output: {sorted(missing)}")
    return result


def split_application_stderr(stderr: str) -> tuple[str, str]:
    lines = stderr.splitlines()
    for index, line in enumerate(lines):
        if line.strip().startswith("Command being timed:"):
            return "\n".join(lines[:index]).strip(), "\n".join(lines[index:])
    raise ComparisonError("/usr/bin/time -v output has no command boundary")


def performance_evidence(path: Path, *, required: bool) -> dict[str, object] | None:
    if not path.is_file():
        if required:
            raise ComparisonError(f"required performance attribution missing: {path}")
        return None
    value = json.loads(path.read_text(encoding="utf-8"))
    if value.get("schema_version") != "trajecta.performance-attribution/v1":
        raise ComparisonError("performance attribution schema identity mismatch")
    stages = value.get("stages")
    if not isinstance(stages, dict):
        raise ComparisonError("performance attribution stages are missing")
    runner_total = stages.get("runner_total")
    runner_output = stages.get("runner_output")
    if not isinstance(runner_total, dict) or not isinstance(runner_output, dict):
        raise ComparisonError("performance attribution omits runner total/output")
    total = runner_total.get("total")
    output = runner_output.get("total")
    if (
        runner_total.get("observations") != 1
        or not isinstance(total, int)
        or not isinstance(output, int)
        or total <= 0
        or output < 0
        or output > total
    ):
        raise ComparisonError("performance attribution runner totals are invalid")
    peak_rss = value.get("process_peak_rss_bytes")
    if required and (not isinstance(peak_rss, int) or peak_rss <= 0):
        raise ComparisonError("performance attribution omits worker peak RSS")
    return {
        "path": str(path),
        "sha256": sha256(path),
        "runner_total_nanoseconds": total,
        "runner_output_nanoseconds": output,
        "equivalent_core_nanoseconds": total - output,
        "process_peak_rss_bytes": peak_rss,
    }


def run_trajecta(arguments: argparse.Namespace) -> int:
    root = arguments.case.resolve()
    case_manifest = root / "M5_A5_TRAJECTA_CASE.json"
    result_path = root / "M5_A5_TRAJECTA_RUN.json"
    if not case_manifest.is_file():
        raise ComparisonError(f"prepared Trajecta case missing: {case_manifest}")
    if result_path.exists():
        raise ComparisonError(f"refusing to overwrite Trajecta run evidence: {result_path}")
    prepared = json.loads(case_manifest.read_text(encoding="utf-8"))
    if prepared.get("schema_version") != TRAJECTA_CASE_SCHEMA_VERSION:
        raise ComparisonError("prepared Trajecta case schema identity mismatch")

    checks = {
        name: False
        for name in (
            "package_identity",
            "project_finalized",
            "run_complete",
            "manifest_complete",
            "abnormal_zero",
            "particle_count",
            "output_schedule",
            "lifecycle",
            "quality",
            "mass_ledger",
            "sqlite_integrity",
            "terminal_wal",
            "full_verify",
            "performance_attribution",
            "daemon_idle",
        )
    }
    failures: list[str] = []
    run: dict[str, object] = {}
    config = root / "config.toml"
    recorder = None
    try:
        identity = product.validate_product_root(arguments.package_root)
        checks["package_identity"] = True
        recorder = product.CommandRecorder(identity, root, arguments.timeout_seconds)
        performance_path = root / "performance-attribution.json"
        recorder.environment["TRAJECTA_PERFORMANCE_ATTRIBUTION_PATH"] = str(performance_path)
        product.configure_runtime(recorder, config)
        project_root = root / "project"
        finalized = recorder.json(
            "project-finalize",
            ["project", "finalize"],
            config=config,
            project=project_root,
        )
        checks["project_finalized"] = finalized.get("data", {}).get("state") == "finalized"

        cli_arguments = [
            "--format",
            "json",
            "--config",
            str(config),
            "--project",
            str(project_root),
            "run",
            "--profile",
            "product",
        ]
        command = [
            "taskset",
            "-c",
            arguments.cpu_set,
            "/usr/bin/time",
            "-v",
            str(identity.binary),
            *cli_arguments,
        ]
        started = time.monotonic_ns()
        try:
            completed = subprocess.run(
                command,
                cwd=root,
                env=recorder.environment,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                timeout=arguments.timeout_seconds,
                check=False,
            )
            timed_out = False
        except subprocess.TimeoutExpired as error:
            completed = subprocess.CompletedProcess(
                command,
                124,
                stdout=error.stdout or b"",
                stderr=error.stderr or b"",
            )
            timed_out = True
        wall_nanoseconds = time.monotonic_ns() - started
        stdout_path = root / "trajecta.stdout.log"
        stderr_path = root / "trajecta.stderr.log"
        stdout_path.write_bytes(completed.stdout)
        stderr_path.write_bytes(completed.stderr)
        if timed_out:
            raise ComparisonError("Trajecta foreground run timed out")
        stderr = completed.stderr.decode("utf-8", errors="replace")
        application_stderr, time_stderr = split_application_stderr(stderr)
        if application_stderr:
            raise ComparisonError("successful Trajecta machine run wrote application stderr")
        time_verbose = parse_time_verbose(time_stderr)
        try:
            envelope = json.loads(completed.stdout)
        except (UnicodeDecodeError, json.JSONDecodeError) as error:
            raise ComparisonError("Trajecta foreground run returned invalid JSON") from error
        if completed.returncode != 0:
            raise ComparisonError(f"Trajecta foreground run exited {completed.returncode}")
        data = envelope.get("data")
        checks["run_complete"] = (
            envelope.get("ok") is True
            and envelope.get("run_success") is True
            and isinstance(data, dict)
            and data.get("state") == "complete"
        )
        if not isinstance(data, dict):
            raise ComparisonError("Trajecta run envelope has no data object")
        output_text = data.get("output_directory")
        series = data.get("job_series_id")
        if not isinstance(output_text, str) or not isinstance(series, str):
            raise ComparisonError("Trajecta run envelope omits output/job identity")
        output_directory = Path(output_text)
        manifest_path = output_directory / "run-manifest.json"
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        checks["manifest_complete"] = manifest.get("status") == "complete"
        checks["abnormal_zero"] = manifest.get("terminations", {}).get("abnormal_count") == 0

        inspection_envelope = recorder.json(
            "result-inspect",
            ["result", "inspect", str(output_directory)],
            config=config,
        )
        inspection = inspection_envelope.get("data", {})
        checks["particle_count"] = (
            inspection.get("particles", {}).get("particle_count") == prepared.get("particles")
        )
        checks["lifecycle"] = inspection.get("lifecycle", {}).get("status") == "complete"
        checks["quality"] = product.quality_is_valid(
            inspection.get("quality"), inspection.get("particles")
        )
        checks["mass_ledger"] = product.mass_ledger_is_valid(manifest, inspection)

        sqlite_path = output_directory / manifest.get("sqlite", {}).get(
            "relative_path", "particles.sqlite"
        )
        sqlite_ok, _particle_id = product.sqlite_audit(
            sqlite_path, manifest.get("sqlite", {}).get("row_counts", {})
        )
        checks["sqlite_integrity"] = sqlite_ok
        wal = sqlite_path.with_name(sqlite_path.name + "-wal")
        checks["terminal_wal"] = not wal.exists() or wal.stat().st_size == 0
        with sqlite3.connect(os.fspath(sqlite_path)) as connection:
            event_times = [
                int(row[0])
                for row in connection.execute(
                    "SELECT physical_seconds FROM output_event ORDER BY event_sequence"
                )
            ]
        output_interval_seconds = int(prepared["output_interval_seconds"])
        checks["output_schedule"] = event_times == list(
            range(START_UNIX, END_UNIX + 1, output_interval_seconds)
        )

        verification = recorder.json(
            "result-verify-full",
            ["result", "verify", series, "--full"],
            config=config,
        ).get("data", {})
        checks["full_verify"] = (
            verification.get("status") == "complete"
            and verification.get("run_success") is True
        )
        attribution = performance_evidence(
            performance_path, required=arguments.require_performance
        )
        checks["performance_attribution"] = attribution is not None or not arguments.require_performance
        runner_milliseconds = (
            product.timestamp_ns(manifest["finished_at"])
            - product.timestamp_ns(manifest["started_at"])
        ) // 1_000_000
        run = {
            "package": {
                "root": str(identity.package_root),
                "source_tree_sha256": identity.source_tree_sha256,
                "build_manifest_sha256": identity.build_manifest_sha256,
                "binary_sha256": identity.binary_sha256,
            },
            "command": command,
            "cpu_set": arguments.cpu_set,
            "exit_code": completed.returncode,
            "wall_nanoseconds": wall_nanoseconds,
            "time_verbose": time_verbose,
            "runner_milliseconds": runner_milliseconds,
            "job_series_id": series,
            "run_id": data.get("run_id"),
            "output_directory": str(output_directory),
            "manifest_sha256": sha256(manifest_path),
            "sqlite_sha256": sha256(sqlite_path),
            "performance_attribution": attribution,
            "stdout_sha256": sha256(stdout_path),
            "stderr_sha256": sha256(stderr_path),
        }
    except (
        ComparisonError,
        product.CommandFailure,
        product.ProductError,
        OSError,
        sqlite3.Error,
        KeyError,
        TypeError,
        ValueError,
    ) as error:
        failures.append(str(error))
    checks["daemon_idle"] = product.wait_for_idle(config) if config.exists() else True
    failures.extend(
        f"check failed: {name}" for name, passed in checks.items() if not passed
    )
    value = {
        "schema_version": "trajecta.m5-a5-trajecta-run/v1",
        "case_manifest_sha256": sha256(case_manifest),
        "checks": checks,
        "failures": failures,
        "run": run,
        "status": "passed" if not failures else "failed",
    }
    write_json(result_path, value)
    print(result_path)
    return 0 if not failures else 1


EARTH_MEAN_RADIUS_M = 6_371_008.8


def _great_circle_distance(numpy, lon1, lat1, lon2, lat2):
    lon1_r = numpy.radians(lon1)
    lat1_r = numpy.radians(lat1)
    lon2_r = numpy.radians(lon2)
    lat2_r = numpy.radians(lat2)
    delta_lon = lon2_r - lon1_r
    delta_lat = lat2_r - lat1_r
    haversine = (
        numpy.sin(delta_lat / 2.0) ** 2
        + numpy.cos(lat1_r) * numpy.cos(lat2_r) * numpy.sin(delta_lon / 2.0) ** 2
    )
    return 2.0 * EARTH_MEAN_RADIUS_M * numpy.arcsin(numpy.sqrt(numpy.clip(haversine, 0, 1)))


def _ensemble_metrics(numpy, longitude, latitude, height) -> dict[str, object]:
    longitude = numpy.asarray(longitude, dtype=numpy.float64).reshape(-1)
    latitude = numpy.asarray(latitude, dtype=numpy.float64).reshape(-1)
    height = numpy.asarray(height, dtype=numpy.float64).reshape(-1)
    finite = numpy.isfinite(longitude) & numpy.isfinite(latitude) & numpy.isfinite(height)
    finite_count = int(finite.sum())
    if finite_count == 0:
        raise ComparisonError("scientific output contains no finite active particles")
    lon = longitude[finite]
    lat = latitude[finite]
    z = height[finite]
    lon_r = numpy.radians(lon)
    lat_r = numpy.radians(lat)
    x = numpy.mean(numpy.cos(lat_r) * numpy.cos(lon_r))
    y = numpy.mean(numpy.cos(lat_r) * numpy.sin(lon_r))
    vertical = numpy.mean(numpy.sin(lat_r))
    centroid_lon = float(numpy.degrees(numpy.arctan2(y, x)))
    centroid_lat = float(numpy.degrees(numpy.arctan2(vertical, numpy.hypot(x, y))))
    source_distance = float(
        _great_circle_distance(numpy, 5.25, 49.25, centroid_lon, centroid_lat)
    )
    dispersion = _great_circle_distance(numpy, centroid_lon, centroid_lat, lon, lat)
    longitude_cell = numpy.floor((numpy.mod(lon + 180.0, 360.0)) / 0.1).astype(numpy.int64)
    latitude_cell = numpy.floor((lat + 90.0) / 0.1).astype(numpy.int64)
    height_cell = numpy.floor(z / 250.0).astype(numpy.int64)
    occupied = len(set(zip(longitude_cell.tolist(), latitude_cell.tolist(), height_cell.tolist())))
    return {
        "coordinate_count": int(longitude.size),
        "finite_count": finite_count,
        "nonfinite_count": int(longitude.size - finite_count),
        "centroid_longitude_degrees": centroid_lon,
        "centroid_latitude_degrees": centroid_lat,
        "centroid_height_asl_m": float(numpy.mean(z)),
        "centroid_distance_from_source_m": source_distance,
        "rms_horizontal_dispersion_m": float(numpy.sqrt(numpy.mean(dispersion ** 2))),
        "height_asl_mean_m": float(numpy.mean(z)),
        "height_asl_standard_deviation_m": float(numpy.std(z)),
        "occupied_audit_cells": occupied,
        "audit_grid": {
            "longitude_degrees": 0.1,
            "latitude_degrees": 0.1,
            "height_m": 250,
        },
    }


def _masked_to_nan(numpy, values):
    if numpy.ma.isMaskedArray(values):
        return numpy.asarray(values.filled(numpy.nan), dtype=numpy.float64)
    return numpy.asarray(values, dtype=numpy.float64)


def scientific_comparison(arguments: argparse.Namespace) -> int:
    output = arguments.output.resolve()
    if output.exists():
        raise ComparisonError(f"refusing to overwrite scientific comparison: {output}")
    flexpart_case = arguments.flexpart_case.resolve()
    trajecta_run_path = arguments.trajecta_run.resolve()
    flexpart_result = json.loads(
        (flexpart_case / "M5_A5_FLEXPART_RUN.json").read_text(encoding="utf-8")
    )
    trajecta_result = json.loads(trajecta_run_path.read_text(encoding="utf-8"))
    if flexpart_result.get("status") != "passed" or trajecta_result.get("status") != "passed":
        raise ComparisonError("scientific comparison requires two passed product runs")
    flexpart_contract = json.loads(
        (flexpart_case / "M5_A5_FLEXPART_CASE.json").read_text(encoding="utf-8")
    )
    trajecta_contract = json.loads(
        (trajecta_run_path.parent / "M5_A5_TRAJECTA_CASE.json").read_text(encoding="utf-8")
    )
    contract_keys = ("time_step_seconds", "output_interval_seconds")
    if any(flexpart_contract.get(key) != trajecta_contract.get(key) for key in contract_keys):
        raise ComparisonError("scientific comparison time contract mismatch")
    output_interval_seconds = int(flexpart_contract["output_interval_seconds"])
    product_files = sorted((flexpart_case / "output").glob("partoutput_*.nc"))
    if len(product_files) != 1:
        raise ComparisonError("FLEXPART product run must contain one particle NetCDF")
    _eccodes, netcdf4, numpy = _stage_modules()
    expected_times = list(
        range(
            START_UNIX + output_interval_seconds,
            END_UNIX + 1,
            output_interval_seconds,
        )
    )
    flexpart_rows: list[dict[str, object]] = []
    with netcdf4.Dataset(product_files[0].as_posix()) as dataset:
        offsets = [int(value) for value in dataset.variables["time"][:]]
        times = [START_UNIX + value for value in offsets]
        if times != expected_times:
            raise ComparisonError(f"FLEXPART product times drifted: {times}")
        particle_count = len(dataset.dimensions["particle"])
        for index, physical_time in enumerate(times):
            longitude = _masked_to_nan(numpy, dataset.variables["lon"][:, index])
            latitude = _masked_to_nan(numpy, dataset.variables["lat"][:, index])
            height = _masked_to_nan(numpy, dataset.variables["z"][:, index])
            topography = _masked_to_nan(numpy, dataset.variables["to"][:, index])
            metrics = _ensemble_metrics(numpy, longitude, latitude, height + topography)
            if metrics["nonfinite_count"] != 0 or metrics["coordinate_count"] != particle_count:
                raise ComparisonError("FLEXPART active/status accounting is ambiguous")
            flexpart_rows.append(
                {
                    "physical_time_unix": physical_time,
                    "active_count": particle_count,
                    "terminated_count": 0,
                    "termination_distribution": {},
                    **metrics,
                }
            )

    trajecta_output = Path(str(trajecta_result["run"]["output_directory"]))
    manifest = json.loads((trajecta_output / "run-manifest.json").read_text(encoding="utf-8"))
    sqlite_path = trajecta_output / manifest.get("sqlite", {}).get(
        "relative_path", "particles.sqlite"
    )
    trajecta_rows: list[dict[str, object]] = []
    with sqlite3.connect(os.fspath(sqlite_path)) as connection:
        particle_count = int(connection.execute("SELECT COUNT(*) FROM particle").fetchone()[0])
        for physical_time in expected_times:
            states = connection.execute(
                "SELECT longitude_degrees, latitude_degrees, height_asl_m, particle_status "
                "FROM particle_state WHERE physical_seconds = ? ORDER BY particle_id",
                (physical_time,),
            ).fetchall()
            active = [row for row in states if row[3] == "alive"]
            metrics = _ensemble_metrics(
                numpy,
                [row[0] for row in active],
                [row[1] for row in active],
                [row[2] for row in active],
            )
            terminations = connection.execute(
                "SELECT classification, reason, COUNT(*) FROM termination "
                "WHERE physical_seconds <= ? GROUP BY classification, reason "
                "ORDER BY classification, reason",
                (physical_time,),
            ).fetchall()
            distribution = {
                f"{classification}:{reason}": int(count)
                for classification, reason, count in terminations
            }
            terminated_count = sum(distribution.values())
            if len(active) + terminated_count != particle_count:
                raise ComparisonError(
                    f"Trajecta lifecycle accounting mismatch at {physical_time}"
                )
            trajecta_rows.append(
                {
                    "physical_time_unix": physical_time,
                    "active_count": len(active),
                    "terminated_count": terminated_count,
                    "termination_distribution": distribution,
                    **metrics,
                }
            )

    cross_rows = []
    for flexpart, trajecta in zip(flexpart_rows, trajecta_rows, strict=True):
        centroid_separation = float(
            _great_circle_distance(
                numpy,
                flexpart["centroid_longitude_degrees"],
                flexpart["centroid_latitude_degrees"],
                trajecta["centroid_longitude_degrees"],
                trajecta["centroid_latitude_degrees"],
            )
        )
        flexpart_dispersion = float(flexpart["rms_horizontal_dispersion_m"])
        flexpart_occupancy = int(flexpart["occupied_audit_cells"])
        cross_rows.append(
            {
                "physical_time_unix": flexpart["physical_time_unix"],
                "horizontal_centroid_separation_m": centroid_separation,
                "vertical_centroid_difference_m": float(
                    trajecta["centroid_height_asl_m"]
                )
                - float(flexpart["centroid_height_asl_m"]),
                "transport_distance_difference_m": float(
                    trajecta["centroid_distance_from_source_m"]
                )
                - float(flexpart["centroid_distance_from_source_m"]),
                "dispersion_width_ratio_trajecta_over_flexpart": (
                    float(trajecta["rms_horizontal_dispersion_m"]) / flexpart_dispersion
                    if flexpart_dispersion > 0
                    else None
                ),
                "occupancy_ratio_trajecta_over_flexpart": (
                    int(trajecta["occupied_audit_cells"]) / flexpart_occupancy
                    if flexpart_occupancy > 0
                    else None
                ),
            }
        )
    value = {
        "schema_version": "trajecta.m5-a5-scientific-comparison/v1",
        "status": "passed",
        "particle_count": particle_count,
        "common_output_times_unix": expected_times,
        "flexpart": flexpart_rows,
        "trajecta": trajecta_rows,
        "cross_model": cross_rows,
        "comparability": {
            "input_source_fields": "exact",
            "encoded_meteorology_values": "aligned",
            "output_instants": "exact",
            "particle_count_and_mass": "exact",
            "longitude_latitude_height_asl": "aligned",
            "ensemble_metrics": "aggregate-only",
            "particle_trajectory_crosswalk": "not-comparable",
            "sqlite_provenance_overhead": "not-comparable",
        },
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    write_json(output, value)
    print(output)
    return 0


def run_flexpart(arguments: argparse.Namespace) -> int:
    case = arguments.case.resolve()
    binary = arguments.binary.resolve()
    manifest_path = case / "M5_A5_FLEXPART_CASE.json"
    result_path = case / "M5_A5_FLEXPART_RUN.json"
    if not binary.is_file():
        raise ComparisonError(f"FLEXPART binary missing: {binary}")
    if not manifest_path.is_file():
        raise ComparisonError(f"prepared case manifest missing: {manifest_path}")
    if result_path.exists():
        raise ComparisonError(f"refusing to overwrite FLEXPART run evidence: {result_path}")
    output = case / "output"
    if not output.is_dir() or any(output.iterdir()):
        raise ComparisonError(f"FLEXPART output directory is absent or nonempty: {output}")

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("schema_version") != SCHEMA_VERSION:
        raise ComparisonError("prepared FLEXPART case schema identity mismatch")

    environment = os.environ.copy()
    environment.update(
        {
            "OMP_NUM_THREADS": "4",
            "OMP_DYNAMIC": "FALSE",
            "OMP_PROC_BIND": "close",
            "OMP_PLACES": "cores",
        }
    )
    command = [
        "taskset",
        "-c",
        arguments.cpu_set,
        "/usr/bin/time",
        "-v",
        str(binary),
        "pathnames",
    ]
    started = time.monotonic_ns()
    try:
        completed = subprocess.run(
            command,
            cwd=case,
            env=environment,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=arguments.timeout_seconds,
            check=False,
        )
        timed_out = False
    except subprocess.TimeoutExpired as error:
        completed = subprocess.CompletedProcess(
            command,
            124,
            stdout=error.stdout or b"",
            stderr=error.stderr or b"",
        )
        timed_out = True
    wall_nanoseconds = time.monotonic_ns() - started
    stdout_path = case / "flexpart.stdout.log"
    stderr_path = case / "flexpart.stderr.log"
    stdout_path.write_bytes(completed.stdout)
    stderr_path.write_bytes(completed.stderr)

    time_evidence = None
    if not timed_out:
        time_evidence = parse_time_verbose(completed.stderr.decode("utf-8", errors="replace"))
    artifacts = []
    for path in sorted(output.rglob("*")):
        if path.is_file():
            artifacts.append(
                {
                    "path": path.relative_to(case).as_posix(),
                    "size_bytes": path.stat().st_size,
                    "sha256": sha256(path),
                }
            )
    result = {
        "schema_version": "trajecta.m5-a5-flexpart-run/v1",
        "case_manifest_sha256": sha256(manifest_path),
        "binary_sha256": sha256(binary),
        "command": command,
        "environment": {
            key: environment[key]
            for key in ("OMP_NUM_THREADS", "OMP_DYNAMIC", "OMP_PROC_BIND", "OMP_PLACES")
        },
        "cpu_set": arguments.cpu_set,
        "timed_out": timed_out,
        "exit_code": completed.returncode,
        "wall_nanoseconds": wall_nanoseconds,
        "time_verbose": time_evidence,
        "stdout_sha256": sha256(stdout_path),
        "stderr_sha256": sha256(stderr_path),
        "artifacts": artifacts,
        "status": "passed" if completed.returncode == 0 and not timed_out else "failed",
    }
    result_path.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(result_path)
    return 0 if result["status"] == "passed" else 1


