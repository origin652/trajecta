def validate_trajecta_data(root: Path) -> list[dict[str, object]]:
    identities = []
    for name, expected in TRAJECTA_DATA_IDENTITIES.items():
        path = root / name
        identity = require_sha256(path, expected)
        identity["path"] = name
        identities.append(identity)
    return identities


